#!/usr/bin/env node
/**
 * Capture the EXACT calldata zSwap.html builds for a cause launch, and write it
 * where a Solidity fork test can replay it against the real SafeSummoner.
 *
 * WHY THIS EXISTS. Everything else that checks the cause launch checks it
 * against a re-reading of the ABI — the UI suite decodes the head and compares
 * word by word, which catches a transposition but cannot catch a shared
 * misunderstanding. If I misread SafeSummoner's struct layout, the page and the
 * test that reads it are wrong in the same direction and both pass.
 *
 * The only thing that settles it is sending those bytes to the deployed
 * contract and looking at what comes out. So the page produces the bytes here,
 * they go into a fixture verbatim, and test/CauseLaunchCalldata.t.sol replays
 * them on a mainnet fork. Nothing in that path re-implements the encoding.
 *
 * The page runs in the same jsdom harness the UI suite uses, so this is the
 * shipped code path and not a copy of it.
 *
 * Usage: node script/dump-cause-calldata.mjs [--out test/fixtures/...]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadPage, MockChain, A } from '../test/ui/harness.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const outArg = (() => { const i = argv.indexOf('--out'); return i > -1 ? argv[i + 1] : null; })();
const OUT = outArg ? path.resolve(outArg) : path.join(ROOT, 'test', 'fixtures', 'cause-launch.json');

// The form the fixture describes. Kept here rather than in the Solidity so the
// two cannot drift: the .t.sol reads these numbers back out of the JSON.
const FORM = {
  name: 'Feed Ducks',
  symbol: 'DUCK',
  goal: '10',      // ETH
  days: '30',      // backing window
  vest: '31556952' // 12 months, the default option's value in seconds
};

const chain = new MockChain();
chain.setNative(A.ACCOUNT, 10n ** 19n);

const page = await loadPage({ chain, fixedRandom: true });
await page.connect();
page.click('ln');
page.select('lnKind', 'cause');
await page.settle();

page.type('lnName', FORM.name);
page.type('lnSym', FORM.symbol);
page.type('lnGoal', FORM.goal);
page.type('lnDays', FORM.days);
page.select('lnVest', FORM.vest);
await page.settle();

page.click('lnGo');
await page.waitFor(() => chain.sent.length > 0, { label: 'the launch transaction' });

const tx = chain.sent.at(-1);
if (!tx) throw new Error('the page sent no transaction');

/* The sale deadline is wall-clock: `now + 30 days`, computed when the page
   built these bytes. It is the one thing here that cannot be compared
   byte-for-byte against a later run, so it is located now and its position
   recorded — the staleness guard masks it rather than guessing where it is.

   It is NOT on the 32-byte word grid: the deadline lives inside the
   ShareOffering.configure payload, which is a `bytes` tail beginning with a
   4-byte selector, so everything after that selector sits at a 4-byte offset
   from the outer words. Scanning the grid finds nothing, which is exactly the
   trap a word-index fixture would have baked in. */
const body = tx.data.slice(10);
const stamp = BigInt(Math.floor(new Date().getTime() / 1000));
const lo = stamp - 86400n, hi = stamp + 400n * 86400n;
let deadlineAt = -1;
for (let c = 0; c + 64 <= body.length; c += 8) {
  const v = BigInt('0x' + body.slice(c, c + 64));
  if (v > lo && v < hi) {
    if (deadlineAt >= 0) throw new Error('more than one window looks like a deadline');
    deadlineAt = c;
  }
}
if (deadlineAt < 0) throw new Error('no deadline found in the calldata');

const fixture = {
  _comment:
    'Generated by script/dump-cause-calldata.mjs from zSwap.html. Do not hand-edit: ' +
    'regenerate it, so the bytes always come from the page rather than from a person.',
  form: FORM,
  to: tx.to,
  value: '0x' + BigInt(tx.value ?? '0x0').toString(16),
  from: A.ACCOUNT,
  data: tx.data,
  // Index of the 32-byte word (after the selector) holding the sale deadline,
  // and the second the page stamped into it.
  // Offset, in hex characters after the selector, of the 32-byte big-endian
  // window holding the sale deadline — plus the second it was stamped with.
  deadlineAt,
  deadline: String(BigInt('0x' + body.slice(deadlineAt, deadlineAt + 64))),
  generatedAt: String(stamp),
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(fixture, null, 2) + '\n');

console.log(`to     ${fixture.to}`);
console.log(`value  ${BigInt(fixture.value)} wei`);
console.log(`data   ${(tx.data.length - 2) / 2} bytes, selector ${tx.data.slice(2, 10)}`);
console.log(`dline  at hex ${deadlineAt}, stamped ${stamp}`);
console.log(`-> ${path.relative(ROOT, OUT)}`);

page.close();
